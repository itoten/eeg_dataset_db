"""Fill empty cells from the free text of a dataset's own record or README, only when the text is unambiguous.

Usage: python3 tools/harvest/text_facts.py [YYYY-MM-DD]

Texts: OpenNeuro README (cache/openneuro), Zenodo record descriptions (cache/zenodo), figshare item
descriptions (cache/repos), NEMAR descriptions and READMEs (cache/nemar/detail). A value is recorded
only if the text yields exactly one distinct value for it (number of participants, sampling rate,
EEG channel count, amplifier maker) and the cell is empty; the locator quotes the sentence. Where the
text disagrees with a value already recorded, nothing is changed and the pair is listed in
cache/text_facts_conflicts.tsv for a person to look at. Evidence rows are checked_by=script.
"""

import datetime
import html
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / ".claude/skills/maintaining-eeg-dataset-db/scripts"))
from reglib import Batch  # noqa: E402

NUM_WORDS = {"ten": 10, "eleven": 11, "twelve": 12, "thirteen": 13, "fourteen": 14, "fifteen": 15, "sixteen": 16, "seventeen": 17, "eighteen": 18,
             "nineteen": 19, "twenty": 20, "thirty": 30, "forty": 40, "fifty": 50}
WHO = r"(?:participants|subjects|volunteers|patients|individuals|children|students|healthy controls?)"
MOD = r"(?:healthy\s+|right-handed\s+|adult\s+|young\s+|older\s+|neurotypical\s+|human\s+)*"
# a number of people is taken only when the sentence goes on with a verb that makes it the total of the study
SUBJ = re.compile(r"(?<![\d.,/-])(\d{1,4}|" + "|".join(NUM_WORDS) + r")\s+" + MOD + WHO +
                  r"\s+(?:\([^)]{0,40}\)\s+)?(?:took part|participated|were recruited|were recorded|were included|completed|underwent|performed|were enrolled)\b", re.I)
FS = re.compile(r"(?:\bsampled at|\bsampling (?:rate|frequency)(?: of| was| is| were| at)?|\bdigiti[sz]ed at)\s*[:=]?\s*(?<![\d.])(\d{2,5}(?:\.\d+)?) ?Hz\b", re.I)
CH = re.compile(r"(?<![\d-])(?<!or )(\d{1,3})[- ]channel\s+EEG\b|(?<![\d-])(\d{1,3})\s+EEG\s+(?:channels|electrodes)\b", re.I)
AMP = r"(?:\s+(?:ActiveTwo|ActiveOne|Active ?Two|amplifiers?|systems?|headsets?|caps?|devices?|Recorder|LiveAmp|actiCHamp|BrainAmp|HIamp|g\.?USBamp|USBamp|Synamps ?2?|HydroCel|Geodesic|Net|Mark IV|Ultracortex|eego|Enobio|Cyton))"
MAKERS = [(r"\bBioSemi\b" + AMP, "BioSemi"), (r"\bBrain ?Products\b|\bBrainAmp\b|\bactiCHamp\b", "Brain Products"), (r"\bg\.tec\b" + AMP, "g.tec"),
          (r"\bNeuroScan\b" + AMP + "?|\bSynAmps\b", "Neuroscan"), (r"\bElectrical Geodesics\b|\bGeodesic Sensor Net\b|\bEGI\b" + AMP, "EGI"), (r"\bEmotiv\b" + AMP + "?", "Emotiv"),
          (r"\bOpenBCI\b", "OpenBCI"), (r"\bNeuroSky\b", "NeuroSky"), (r"\bEnobio\b", "Neuroelectrics"), (r"\bANT ?Neuro\b" + AMP + "?|\beego(?:sports|mylab)?\b", "ANT Neuro"),
          (r"\bNihon Kohden\b", "Nihon Kohden"), (r"\bNatus\b|\bNicolet\b", "Natus"), (r"\bCompumedics\b", "Compumedics"), (r"\bCognionics\b", "Cognionics"),
          (r"\bWearable Sensing\b|\bDSI-24\b", "Wearable Sensing"), (r"\bNeuracle\b", "Neuracle"), (r"\bBitbrain\b", "Bitbrain"), (r"\bMitsar\b", "Mitsar"), (r"\bBiopac\b", "Biopac")]


def clean(t):
    return " ".join(html.unescape(re.sub(r"<[^>]+>", " ", t or "")).split())


def sentence(text, m):
    """The words around the match (at most 25), always including it."""
    a, b = max(0, m.start() - 90), min(len(text), m.end() + 90)
    words = text[a:b].split()
    k = len(text[a:m.start()].split())
    lo = max(0, k - 10)
    return " ".join(words[lo:lo + 25])


def one(matches, conv):
    vals = {}
    for m in matches:
        v = conv(m)
        if v is not None:
            vals.setdefault(v, m)
    return vals


def facts(text):
    out = {}
    if re.search(r"\b(synthetic|simulated|artificially generated|generated by)\b", text, re.I):
        return out  # a dataset of generated signals states facts about the generator, not recordings
    s = one(SUBJ.finditer(text), lambda m: NUM_WORDS.get(m.group(1).lower()) or (int(m.group(1)) if m.group(1).isdigit() and 1 < int(m.group(1)) < 5000 else None))
    if len(s) == 1:
        v, m = next(iter(s.items()))
        out["n_subjects_reported"] = (str(v), sentence(text, m))
    multi = re.search(r"\b(two|three|four|five|several|multiple|different|various)\s+(?:recording |EEG |acquisition )?(systems|setups|devices|amplifiers|sites|centers|centres|cohorts|datasets)\b", text, re.I)
    f = one(FS.finditer(text), lambda m: float(m.group(1)))
    if len(f) == 1 and not multi and not re.search(r"re-?sampl|down-?sampl|up-?sampl|decimat", text, re.I):
        v, m = next(iter(f.items()))
        near = text[max(0, m.start() - 120):m.end() + 60]
        if re.search(r"\bEEG\b|electroenceph", near, re.I) and not re.search(r"\b(ECG|EDA|EMG|EOG|fMRI|stimul|video|refresh|display|eye[- ]track|accelerom)", near, re.I):
            out["sampling_rate_hz"] = (f"{v:g}", sentence(text, m))
    c = one(CH.finditer(text), lambda m: int(next(g for g in m.groups() if g)))
    if len(c) == 1 and not multi:
        v, m = next(iter(c.items()))
        if 1 <= v <= 512:
            out["n_channels_eeg"] = (str(v), sentence(text, m))
    return out


def texts():
    for p in sorted((ROOT / "cache" / "openneuro").glob("ds*.json")):
        d = json.loads(p.read_text())["dataset"]
        t = clean((d.get("latestSnapshot") or {}).get("readme"))
        if t:
            yield d["id"].lower(), f"{d['id'].lower()}_record", t, "README"
    best = {}
    for p in (ROOT / "cache" / "zenodo").glob("*.json"):
        if not p.stem.isdigit():
            continue
        d = json.loads(p.read_text())
        c = str(d.get("conceptrecid") or d["id"])
        if c not in best or d["metadata"].get("publication_date", "") > best[c]["metadata"].get("publication_date", ""):
            best[c] = d
    for c, d in best.items():
        t = clean(d["metadata"].get("description"))
        if t:
            yield f"zenodo_{c}", f"zenodo_{d['id']}", t, "Description"
    for p in sorted((ROOT / "cache" / "repos").glob("figshare_*.json")):
        d = json.loads(p.read_text())
        t = d.get("desc") or ""
        yield "@fig:" + p.stem, None, t, "Description"
    for p in sorted((ROOT / "cache" / "nemar" / "detail").glob("nm*.json")):
        d = json.loads(p.read_text())["dataset"]
        t = clean((d.get("description") or "") + " " + (d.get("readme") or ""))
        if t:
            yield d["dataset_id"], f"{d['dataset_id']}_nemar", t, "Record description and README"


def main():
    today = sys.argv[1] if len(sys.argv) > 1 else datetime.date.today().isoformat()
    B = Batch(today)
    db = B.db
    have = {d["dataset_id"]: d for d in db["datasets"][1]}
    srcs = {s["source_id"] for s in db["sources"][1]}
    setups = {(r["dataset_id"], r["setup_id"]): r for r in db["acquisition_setups"][1]}
    fig = {}
    for e in json.loads((ROOT / "cache" / "figshare" / "entries.json").read_text()):
        fig[f"figshare_article_{e['id']}"] = e["dataset_id"]
    conflicts, n = [], 0
    for did, sid, text, label in texts():
        if did.startswith("@fig:"):
            did = fig.get(did[5:])
            sid = f"{did}_figshare" if did else None
        if not did or did not in have or sid not in srcs:
            continue
        for field, (val, loc) in facts(text).items():
            if field == "n_subjects_reported":
                cur, key = have[did]["n_subjects_reported"], "n_subjects_reported"
            else:
                row = setups.get((did, "main"))
                col = field
                cur, key = (row or {}).get(col, ""), f"acquisition_setups:main.{col}"
            if cur and cur != val:
                if cur not in ("unknown", "NA", "conflicting"):
                    conflicts.append((did, field, cur, val))
                continue
            if cur:
                continue
            R = B.dataset(did)
            if field != "n_subjects_reported" and (did, "main") not in setups:
                setups[(did, "main")] = R.child("acquisition_setups", "main", description="As stated in the record's free text")
            R.ev(key, val, sid, f"{label}: {loc}", "script")
            if field != "n_subjects_reported":
                setups[(did, "main")][field] = val
            n += 1
    B.save()
    (ROOT / "cache" / "text_facts_conflicts.tsv").write_text("\n".join("\t".join(c) for c in conflicts) + "\n")
    print(f"{n} values recorded; {len(conflicts)} disagreements left for a person (cache/text_facts_conflicts.tsv)")


if __name__ == "__main__":
    main()
